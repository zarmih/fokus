const DOMAINS = new Set(['attention', 'memory', 'speed', 'flexibility', 'logic']);

export function exerciseIconSrc(id: string | undefined, domain?: string, base: string = import.meta.env.BASE_URL): string {
  if (id && EXERCISE_ICON_IDS.has(id)) return `${base}art/icon-${id}.svg`;
  const d = domain && DOMAINS.has(domain) ? domain : 'attention';
  return `${base}art/icon-domain-${d}.svg`;
}
