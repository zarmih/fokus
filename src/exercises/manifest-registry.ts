import type { ExerciseManifest } from './contract';
import { MANIFESTS } from './manifests.generated';

/**
 * Lightweight registry for the app shell: manifests only (id, name, domain, skills, instruction).
 * Exercise views are code-split and loaded on demand via loadExercise(); the full module registry
 * (./registry) is for tests and tooling. A unit test keeps the generated data in sync.
 */
export const registry: { manifest: ExerciseManifest }[] = MANIFESTS.map((manifest) => ({ manifest }));

export function serializeManifests(list: ExerciseManifest[]): string {
  // Faithful JSON copy (incl. level tables used for maxLevel); functions, if any, are not data.
  const rows = list.map((m) => JSON.parse(JSON.stringify(m)));
  return `// Generated by \`npm run gen:manifests\` from src/exercises/registry.ts — do not edit by hand.
import type { ExerciseManifest } from './contract';

export const MANIFESTS = ${JSON.stringify(rows, null, 1)} as unknown as ExerciseManifest[];
`;
}
